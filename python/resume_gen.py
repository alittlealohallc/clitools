class ResumePDF(FPDF):
    def __init__(self, font_name):
        super().__init__(orientation="P", unit="mm", format="Letter")
        self.font_name = font_name
        self.set_margins(MARGIN_MM, MARGIN_MM, MARGIN_MM)
        self.set_auto_page_break(auto=True, margin=MARGIN_MM)
        
        font_map, _ = get_font_map()
        for style, path in font_map.items():
            self.add_font(font_name, style, path, uni=True)

    def draw_header(self, name, contact_lines):
        self.set_font(self.font_name, "B", 14)
        self.set_text_color(0, 0, 0)
        self.cell(0, 8, name, ln=True, align="C")
        
        self.set_font(self.font_name, "", FONT_SIZE_CONTACT)
        self.set_text_color(60, 60, 60)
        for line in contact_lines:
            self.cell(0, 5, line, ln=True, align="C")
        self.ln(4)

    def section_heading(self, text):
        self.ln(3)
        self.set_font(self.font_name, "B", FONT_SIZE_HEADER)
        self.set_text_color(0, 0, 0)
        self.cell(0, 6, text.upper(), ln=True)
        self.ln(1)

    def render_html(self, html_content):
        if not html_content:
            return
        html_content = html_content.replace('<br>', '\n').replace('<br/>', '\n')
        lines = html_content.split('\n')
        
        for line in lines:
            line = line.strip()
            if not line:
                continue
            
            if line.startswith('<h1>'):
                txt = re.sub(r'<[^>]+>', '', line)
                self.set_font(self.font_name, "B", 14)
                self.cell(0, 6, txt, ln=True)
                self.ln(2)
            elif line.startswith('<h2>'):
                txt = re.sub(r'<[^>]+>', '', line)
                self.section_heading(txt)
            elif line.startswith('<h3>'):
                txt = re.sub(r'<[^>]+>', '', line)
                self.set_font(self.font_name, "B", 11)
                self.cell(0, 5, txt, ln=True)
                self.ln(1)
            elif line.startswith('<hr'):
                self.line(self.x, self.y, self.w - self.r_margin, self.y)
                self.ln(2)
            elif line.startswith('<li>'):
                txt = re.sub(r'<[^>]+>', '', line)
                self.set_font(self.font_name, "", FONT_SIZE_BODY)
                self.set_text_color(0, 0, 0)
                bullet = "\u2022"
                bw = self.get_string_width(bullet + " ")
                self.cell(bw, 5, bullet, ln=False)
                self.multi_cell(self.w - self.l_margin - self.r_margin - bw, 5, txt, ln=True)
            elif line.startswith('<p>') or line.startswith('<div>'):
                txt = re.sub(r'<[^>]+>', '', line)
                if txt:
                    self.set_font(self.font_name, "", FONT_SIZE_BODY)
                    self.set_text_color(0, 0, 0)
                    self.multi_cell(self.w - self.l_margin - self.r_margin, 5, txt, ln=True)
            else:
                if line:
                    self.set_font(self.font_name, "", FONT_SIZE_BODY)
                    self.set_text_color(0, 0, 0)
                    self.multi_cell(self.w - self.l_margin - self.r_margin, 5, line, ln=True)

