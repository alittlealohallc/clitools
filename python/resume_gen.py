#!/usr/bin/env python3
"""
Resume & Cover Letter PDF Generator (v2.1)
Features:
  - Auto-detects Resume vs Cover Letter order and swaps them.
  - Fallback parser if 'markdown' library is missing.
  - Unified Header extraction.
  - --setup: Creates a shell wrapper 'resume-gen' in ~/bin.
"""

import os
import sys
import argparse
import re
import subprocess
from pathlib import Path

# Try to import markdown, but define a fallback if it fails
try:
    import markdown
    HAS_MARKDOWN = True
except ImportError:
    HAS_MARKDOWN = False
    print("⚠️  WARNING: 'markdown' library not found. Using built-in fallback parser.")
    print("   To fix: python3 -m pip install markdown")

try:
    from fpdf import FPDF
except ImportError:
    print("ERROR: Missing dependency: fpdf2")
    print("Install with: python3 -m pip install fpdf2")
    sys.exit(1)

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

MARGIN_IN = 0.7
MARGIN_MM = MARGIN_IN * 25.4
PAGE_W_MM = 215.9
PAGE_H_MM = 279.4

FONT_NAME = "Cambria"
FONT_SIZE_BODY = 11
FONT_SIZE_HEADER = 12
FONT_SIZE_CONTACT = 10

# Font Paths
WORD_DFONT_BASE = "/Applications/Microsoft Word.app/Contents/Resources/DFonts"
CAMBRIA_FONTS = {
    "":   os.path.join(WORD_DFONT_BASE, "Cambria.ttc"),
    "B":  os.path.join(WORD_DFONT_BASE, "Cambriab.ttf"),
    "I":  os.path.join(WORD_DFONT_BASE, "Cambriai.ttf"),
    "BI": os.path.join(WORD_DFONT_BASE, "Cambriaz.ttf"),
}

TIMES_PATHS = [
    "/Library/Fonts/Times New Roman.ttf",
    os.path.expanduser("~/Library/Fonts/Times New Roman.ttf"),
    "C:/Windows/Fonts/times.ttf",
]

# Separators
MARKDOWN_SEPARATOR = "<!-- COVER LETTER START -->"
DOUBLE_DASH_SEPARATOR = "---\n---"

# ---------------------------------------------------------------------------
# Helper Functions
# ---------------------------------------------------------------------------

def find_font(paths):
    for p in paths:
        if os.path.exists(p):
            return p
    return None

def get_font_map():
    if all(os.path.exists(p) for p in CAMBRIA_FONTS.values()):
        return CAMBRIA_FONTS, FONT_NAME
    else:
        times = find_font(TIMES_PATHS)
        if times:
            return {"": times, "B": times, "I": times, "BI": times}, "TimesNewRoman"
        else:
            print("ERROR: Could not find Cambria or Times New Roman.")
            sys.exit(1)

def setup_wrapper():
    """
    Creates a shell wrapper script 'resume-gen' in ~/bin.
    The wrapper calls this script with all arguments passed to it.
    """
    # Get absolute path to THIS script
    script_path = os.path.abspath(__file__)
    
    # Determine target directory
    # You can change this to ~/.local/bin if you prefer
    bin_dir = os.path.expanduser("~/bin")
    wrapper_name = "resume-gen"
    wrapper_path = os.path.join(bin_dir, wrapper_name)
    
    # Ensure bin directory exists
    if not os.path.exists(bin_dir):
        os.makedirs(bin_dir)
        print(f"Created directory: {bin_dir}")
    
    # Remove existing file/link if present
    if os.path.islink(wrapper_path) or os.path.exists(wrapper_path):
        os.remove(wrapper_path)
        print(f"Removed existing: {wrapper_path}")
    
    # Create the shell wrapper content
    # We use $@ to pass all arguments
    wrapper_content = f"""#!/bin/zsh
# Wrapper for resume_gen.py
# Generated by resume_gen.py --setup

exec "{sys.executable}" "{script_path}" "$@"
"""
    
    # Write the wrapper
    with open(wrapper_path, 'w') as f:
        f.write(wrapper_content)
    
    # Make it executable
    os.chmod(wrapper_path, 0o755)
    
    print(f"✅ Wrapper created: {wrapper_path}")
    print(f"   Content: exec '{sys.executable}' '{script_path}' \"$@\"")
    print(f"   You can now run 'resume-gen <file.md>' from anywhere.")
    print(f"   Note: Ensure {bin_dir} is in your PATH.")
    
    # Check PATH
    current_path = os.environ.get('PATH', '')
    if bin_dir not in current_path:
        print(f"\n⚠️  WARNING: {bin_dir} is not in your PATH.")
        print(f"   Add this to your ~/.zshrc:")
        print(f"   export PATH=\"{bin_dir}:$PATH\"")
        print(f"   Then run: source ~/.zshrc")

