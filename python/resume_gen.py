def extract_header_info(text_block):
    """Extracts Name and Contact info from the top of a text block."""
    lines = text_block.strip().split('\n')
    name = ""
    contact_lines = []
    idx = 0
    
    while idx < len(lines) and not lines[idx].strip():
        idx += 1
    
    if idx >= len(lines):
        return "", [], text_block

    name = lines[idx].strip()
    idx += 1
    
    while idx < len(lines) and len(contact_lines) < 3:
        line = lines[idx].strip()
        if not line:
            idx += 1
            continue
        
        if '@' in line or '.' in line or '+' in line or '(' in line or len(line) < 80:
            if line.startswith('#'):
                break
            contact_lines.append(line)
        else:
            break
        idx += 1
        
    remaining = '\n'.join(lines[idx:])
    return name, contact_lines, remaining

def split_document(content):
    """Detects and splits Resume/Cover Letter, ensuring Cover Letter is first."""
    content = content.replace('\r\n', '\n')
    
    sep_idx = -1
    sep_type = None
    
    if MARKDOWN_SEPARATOR in content:
        sep_idx = content.find(MARKDOWN_SEPARATOR)
        sep_type = "MARKDOWN"
    elif DOUBLE_DASH_SEPARATOR in content:
        sep_idx = content.find(DOUBLE_DASH_SEPARATOR)
        sep_type = "DOUBLE_DASH"
    
    if sep_idx == -1:
        return content, "", "single"

    part1 = content[:sep_idx].strip()
    part2 = content[sep_idx + len(sep_type == "DOUBLE_DASH" and DOUBLE_DASH_SEPARATOR or MARKDOWN_SEPARATOR):].strip()
    
    p1_lower = part1.lower()
    p2_lower = part2.lower()
    
    is_p1_resume = any(k in p1_lower for k in ["experience", "skills", "education", "professional"])
    is_p1_letter = any(k in p1_lower for k in ["dear", "sincerely", "date", "cover letter"])
    is_p2_resume = any(k in p2_lower for k in ["experience", "skills", "education", "professional"])
    is_p2_letter = any(k in p2_lower for k in ["dear", "sincerely", "date", "cover letter"])
    
    cover_text = ""
    resume_text = ""
    
    if is_p1_letter and is_p2_resume:
        cover_text = part1
        resume_text = part2
    elif is_p1_resume and is_p2_letter:
        cover_text = part2
        resume_text = part1
    elif is_p1_letter and not is_p2_resume:
        cover_text = part1
        resume_text = part2
    elif is_p2_letter and not is_p1_resume:
        cover_text = part2
        resume_text = part1
    else:
        if is_p2_letter:
            cover_text = part2
            resume_text = part1
        else:
            cover_text = part1
            resume_text = part2

    return cover_text, resume_text, "split"

def parse_markdown_fallback(text):
    """Simple regex-based parser if 'markdown' lib is missing."""
    html = ""
    lines = text.split('\n')
    in_list = False
    
    for line in lines:
        stripped = line.strip()
        if not stripped:
            if in_list: html += "</ul>\n"; in_list = False
            html += "<p></p>"
            continue
        
        if stripped.startswith('### '):
            if in_list: html += "</ul>\n"; in_list = False
            html += f"<h3>{stripped[4:]}</h3>\n"
        elif stripped.startswith('## '):
            if in_list: html += "</ul>\n"; in_list = False
            html += f"<h2>{stripped[3:]}</h2>\n"
        elif stripped.startswith('# '):
            if in_list: html += "</ul>\n"; in_list = False
            html += f"<h1>{stripped[2:]}</h1>\n"
        elif stripped.startswith('**') and stripped.endswith('**'):
            html += f"<p><strong>{stripped[2:-2]}</strong></p>\n"
        elif stripped.startswith('- ') or stripped.startswith('* '):
            if not in_list:
                html += "<ul>\n"
                in_list = True
            txt = re.sub(r'^[-*]\s+', '', stripped)
            txt = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', txt)
            txt = re.sub(r'\*(.*?)\*', r'<em>\1</em>', txt)
            html += f"<li>{txt}</li>\n"
        else:
            if in_list:
                html += "</ul>\n"
                in_list = False
            txt = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', stripped)
            txt = re.sub(r'\*(.*?)\*', r'<em>\1</em>', txt)
            html += f"<p>{txt}</p>\n"
            
    if in_list:
        html += "</ul>\n"
    return html

def convert_to_html(text):
    if not text.strip():
        return ""
    if HAS_MARKDOWN:
        md = markdown.Markdown(extensions=['extra', 'codehilite'])
        return md.convert(text)
    else:
        return parse_markdown_fallback(text)

